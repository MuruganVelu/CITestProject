import type { AgentContext } from "../framework/AgentContext.js";
import type { GeneratedDocument } from "../framework/types.js";

export function buildOnboardingDoc(ctx: AgentContext): GeneratedDocument {
  const jira = ctx.artifacts.filter((a) => a.type === "jira");
  const tests = ctx.artifacts.filter((a) => a.type === "test-case");
  const md = `# ${ctx.applicationName} — Induction & Onboarding Guide

**Audience:** ${ctx.audience}  
**Generated:** ${new Date().toISOString().split("T")[0]}

## 1. Purpose

This guide accelerates onboarding by consolidating Jira stories, functional tests, and requirements into a single narrative.

## 2. Application at a glance

| Metric | Value |
|--------|-------|
| Jira items ingested | ${jira.length} |
| Test artifacts ingested | ${tests.length} |
| Total knowledge sources | ${ctx.artifacts.length} |

## 3. Key features (from Jira)

${jira.length ? jira.map((j) => `- **${j.title}** — ${j.summary}`).join("\n") : "_No Jira data — export issues to JSON and re-run ingest._"}

## 4. How we validate behavior (tests)

${tests.length ? tests.map((t) => `- **${t.title}**: ${t.summary}`).join("\n") : "_No test cases linked yet._"}

## 5. First-week checklist

1. Read functional overview (functional-overview.md).
2. Walk through critical user journeys listed in Jira stories.
3. Run the automation smoke suite (see \`automation-context.md\`).
4. Pair with a domain expert on gaps flagged in gap analysis.

## 6. Contacts & escalation

_Define product owner, QA lead, and automation lead for ${ctx.applicationName}._

---
_Auto-generated by AI Knowledge Documentation Agent (Use Case 3)._
`;
  return { kind: "onboarding", title: `${ctx.applicationName} Onboarding`, markdown: md };
}

export function buildFunctionalOverviewDoc(ctx: AgentContext): GeneratedDocument {
  const stories = ctx.artifacts.filter((a) => a.type === "jira");
  const reqs = ctx.artifacts.filter(
    (a) => a.type === "requirement" || a.type === "existing-doc",
  );

  const md = `# ${ctx.applicationName} — Functional Overview

## Requirements baseline

${reqs.map((r) => `### ${r.title}\n\n${r.rawExcerpt.slice(0, 800)}\n`).join("\n") || "_Add requirements markdown or text files to sources._"}

## User stories & acceptance context

${stories
  .map(
    (s) => `### ${s.title}

**Type / status:** ${s.metadata.issueType ?? "—"} / ${s.metadata.status ?? "—"}

${s.rawExcerpt}
`,
  )
  .join("\n")}

## Cross-cutting rules

- Map each story to at least one functional or automated test.
- Keep this document updated when Jira status moves to *Done*.

---
_Auto-generated functional documentation._
`;
  return {
    kind: "functional-overview",
    title: `${ctx.applicationName} Functional Overview`,
    markdown: md,
  };
}

export function buildAutomationContextDoc(ctx: AgentContext): GeneratedDocument {
  const tests = ctx.artifacts.filter((a) => a.type === "test-case");
  const md = `# ${ctx.applicationName} — Automation Context Pack

Use this pack when writing or maintaining automated tests (e.g. Selenium + TestNG).

## Suites & classes

${tests
  .map(
    (t) => `## ${t.title}

- **Summary:** ${t.summary}
- **Classes:** ${t.metadata.classes ?? "—"}
- **Methods:** ${t.metadata.methods ?? "—"}

\`\`\`
${t.rawExcerpt.slice(0, 1200)}
\`\`\`
`,
  )
  .join("\n")}

## Suggested automation workflow

1. Pick a Jira key from functional overview.
2. Locate or create a TestNG method covering the acceptance criteria.
3. Use page objects and shared fixtures (align with \`MavenAutoTest\` patterns in this repo).
4. Attach test evidence back to the Jira story.

## Context for AI-assisted script generation

When prompting an AI coding assistant, include:

- This file plus the relevant Jira excerpt.
- DOM selectors or API contracts from existing tests.
- Expected assertions and test data boundaries.

---
_Auto-generated automation context._
`;
  return {
    kind: "automation-context",
    title: `${ctx.applicationName} Automation Context`,
    markdown: md,
  };
}
